#!/usr/bin/env python3
"""Vendored client libraries (KaTeX, Mermaid).

    scripts/vendor.py                      regenerate src/vendor.rs from assets/vendor
    scripts/vendor.py update [KATEX] [MERMAID]
                                           download the libraries from jsDelivr (version
                                           specs like 0.16 / 11 / 11.17.2), then regenerate

Only what the page needs is kept: katex.min.js, katex.min.css and the woff2 fonts the
CSS references, plus the single-file mermaid.min.js bundle.
"""

import json
import pathlib
import re
import sys
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
VENDOR = ROOT / "assets" / "vendor"
OUT = ROOT / "src" / "vendor.rs"
CDN = "https://cdn.jsdelivr.net/npm/"
MIME = {
    ".js": "application/javascript; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".woff2": "font/woff2",
}
SKIP = {"LICENSE", "VERSIONS"}


def fetch(url: str) -> bytes:
    with urllib.request.urlopen(url, timeout=120) as r:
        return r.read()


def save(rel: str, data: bytes) -> None:
    path = VENDOR / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)
    print(f"  {rel} ({len(data) // 1024} KB)")


def resolve(pkg: str, spec: str) -> str:
    return json.loads(fetch(f"{CDN}{pkg}@{spec}/package.json"))["version"]


def update(katex_spec: str, mermaid_spec: str) -> None:
    kv, mv = resolve("katex", katex_spec), resolve("mermaid", mermaid_spec)
    print(f"katex {kv}, mermaid {mv}")
    for p in VENDOR.rglob("*"):
        if p.is_file():
            p.unlink()

    css = fetch(f"{CDN}katex@{kv}/dist/katex.min.css")
    save("katex/katex.min.css", css)
    save("katex/katex.min.js", fetch(f"{CDN}katex@{kv}/dist/katex.min.js"))
    fonts = sorted(set(re.findall(r"fonts/(KaTeX_[A-Za-z0-9-]+\.woff2)", css.decode())))
    for f in fonts:
        save(f"katex/fonts/{f}", fetch(f"{CDN}katex@{kv}/dist/fonts/{f}"))
    save("katex/LICENSE", fetch(f"{CDN}katex@{kv}/LICENSE"))

    save("mermaid/mermaid.min.js", fetch(f"{CDN}mermaid@{mv}/dist/mermaid.min.js"))
    save("mermaid/LICENSE", fetch(f"{CDN}mermaid@{mv}/LICENSE"))
    (VENDOR / "VERSIONS").write_text(f"katex {kv}\nmermaid {mv}\n")


def generate() -> None:
    files = sorted(p for p in VENDOR.rglob("*") if p.is_file() and p.name not in SKIP)
    lines = [
        "//! Vendored client libraries (KaTeX, Mermaid), embedded into the binary and served",
        "//! at `mdview://localhost/static/<path>`. Generated by scripts/vendor.py from assets/vendor/.",
        "",
        "pub const STATIC_FILES: &[(&str, &str, &[u8])] = &[",
    ]
    for p in files:
        rel = p.relative_to(VENDOR).as_posix()
        mime = MIME.get(p.suffix)
        if mime is None:
            sys.exit(f"unknown file type: {rel}")
        lines.append(f'    ("{rel}", "{mime}", include_bytes!("../assets/vendor/{rel}")),')
    lines += [
        "];",
        "",
        "pub fn lookup(path: &str) -> Option<(&'static str, &'static [u8])> {",
        "    STATIC_FILES",
        "        .iter()",
        "        .find(|(name, _, _)| *name == path)",
        "        .map(|(_, mime, bytes)| (*mime, *bytes))",
        "}",
        "",
    ]
    OUT.write_text("\n".join(lines))
    print(f"{OUT.relative_to(ROOT)}: {len(files)} files")


if __name__ == "__main__":
    args = sys.argv[1:]
    if args and args[0] == "update":
        update(args[1] if len(args) > 1 else "0.16", args[2] if len(args) > 2 else "11")
    elif args:
        sys.exit(__doc__)
    generate()
